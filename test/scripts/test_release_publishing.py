def workflow_config(*, smoke_test: bool) -> dict[str, Any]:
    return {"methods": ["alpha"], "smoke_test": smoke_test}


def build_output_tree(
    root: Path,
    *,
    plot: bytes = b"%PDF-1.4 plot",
    datasets: Sequence[str] = ("cube",),
    smoke_test: bool = False,
    code: Mapping[Stage, CodeIdentity] | None = None,
) -> None:
    write_catalog(
        root,
        Catalog(
            methods=[ALPHA_HARD_ONLY],
            datasets=list(datasets),
            smoke_test=smoke_test,
            code=code or {},
        ),
    )
    (root / PLOT).parent.mkdir(parents=True)
    (root / PLOT).write_bytes(plot)


def reviewed_checkout(tmp_path: Path, reviews: Mapping[str, str]) -> Path:
    """Write a checkout whose redistribution reviews give each status."""
    checkout = tmp_path / "checkout"
    review_file = checkout / "conf/release/dataset_redistribution.yaml"
    review_file.parent.mkdir(parents=True)
    review_file.write_text(
        yaml.safe_dump(
            {
                "datasets": {
                    dataset: {
                        "status": status,
                        "license": "MIT",
                        "source": "generated by afabench",
                        "reviewed_by": "maintainer",
                        "notes": None,
                    }
                    for dataset, status in reviews.items()
                }
            }
        )
    )
    return checkout


def prepare_package(
    tmp_path: Path,
    release_id: str,
    *,
    scope: str = "full",
    smoke_test: bool = False,
    plot: bytes = b"%PDF-1.4 plot",
    datasets: Sequence[str] = ("cube",),
    checkout: Path | None = None,
    code: Mapping[Stage, CodeIdentity] | None = None,
) -> Path:
    """
    Save a snapshot with a release manifest, as a maintainer would.

    Unless `checkout` is given, every dataset is reviewed as permitted.
    """
    source_root = tmp_path / f"{release_id}-source"
    build_output_tree(
        source_root,
        plot=plot,
        datasets=datasets,
        smoke_test=smoke_test,
        code=code,
    )
    configfile = tmp_path / f"{release_id}.yaml"
    configfile.write_text(
        yaml.safe_dump(workflow_config(smoke_test=smoke_test))
    )
    record_run_config(source_root, configfile)
    if checkout is None:
        checkout = reviewed_checkout(
            tmp_path / release_id, dict.fromkeys(datasets, "permitted")
        )
    package_dir = tmp_path / f"{release_id}-package"
    result = runner.invoke(
        app,
        [
            "save",
            str(package_dir),
            "--source-root",
            str(source_root),
            "--configfile",
            str(configfile),
            "--release-id",
            release_id,
            "--scope",
            scope,
            "--checkout",
            str(checkout),
        ],
    )
    assert result.exit_code == 0, result.output
    return package_dir


def invoke(transport: FakeReleaseTransport, *args: str) -> Result:
    return runner.invoke(
        app,
        [*args, "--repo-id", REPO_ID],
        obj=lambda _repo_id: transport,
    )


def download(
    transport: FakeReleaseTransport,
    release_id: str,
    destination_root: Path,
    *extra: str,
) -> Result:
    return invoke(
        transport,
        "download",
        release_id,
        "--all",
        "--destination-root",
        str(destination_root),
        *extra,
    )


def test_published_release_downloads_with_native_tables_and_plots(
    tmp_path: Path,
) -> None:
    transport = FakeReleaseTransport()
    package_dir = prepare_package(tmp_path, "2026-10-cube")
    destination_root = tmp_path / "fork/output"

    published = invoke(transport, "publish", str(package_dir))
    downloaded = download(transport, "2026-10-cube", destination_root)

    assert published.exit_code == 0, published.output
    assert downloaded.exit_code == 0, downloaded.output
    source_root = package_dir / "output"
    for path in [RAW_TABLE, TRANSFORMED_TABLE, PLOT]:
        assert (destination_root / path).read_bytes() == (
            source_root / path
        ).read_bytes()
    for path in [RAW_TABLE, TRANSFORMED_TABLE]:
        table = pd.read_parquet(destination_root / path)
        assert table["afa_method"].unique().tolist() == ["alpha"]
    manifest = read_release_manifest(
        destination_root / "release_manifest.json"
    )
    assert manifest.release_id == "2026-10-cube"
    assert manifest.evaluations[0].raw_path == RAW_TABLE
    assert "Release 2026-10-cube" in downloaded.output


