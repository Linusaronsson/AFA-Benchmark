"""
A restored release's config invocation is planned as its preview (#160).

The release is a catalog of artifacts with provenance records, saved and
restored as an adopter downloads it, in the harness's checkout. The plans
come from the interactive preview's planning child over the launcher's
arguments for `--configfile <output root>/benchmark.yaml`, the actual
release-aware planner path. Released outputs on datasets that dataset
generation must regenerate first are conditionally reused; preview neither
runs a job nor writes into the output root.
"""

import asyncio
import shutil
import time
from pathlib import Path
from typing import Literal

import yaml
from typer.testing import CliRunner

from afabench.pipeline_plan.planning import PipelinePlan
from afabench.pipeline_preview.app import PipelinePreviewApp
from afabench.pipeline_preview.planning_process import PlanningProcess
from scripts.release.snapshot import app
from test.scripts.release_artifacts import (
    HARD_3,
    Catalog,
    Method,
    evaluation_table,
    record_run_config,
    write_catalog,
)
from test.workflow.submission_harness import WorkflowHarness

type Key = tuple[str, str | None, str]

RELEASED_METHOD = Method(name="alpha", budgets=[HARD_3])
RELEASED_EVALUATION = evaluation_table(RELEASED_METHOD, "cube", 0, HARD_3)
# The launcher's arguments of the release's config invocation
RELEASE = ("--configfile", "output/smoke/benchmark.yaml")
# The same extended with beta and a second dataset realization
EXTENDED_RELEASE = (
    *RELEASE,
    "methods=[alpha,beta]",
    "dataset_realization_indices=[0,1]",
)


def restored_release(
    root: Path, *, dataset_bundles: Literal["include", "omit"]
) -> WorkflowHarness:
    """Restore a release of alpha on cube into the harness's output root."""
    workflow = WorkflowHarness(root / "checkout")
    # The release brings its own datasets and classifier.
    shutil.rmtree(workflow.output)
    workflow.config.update(
        methods=["alpha"],
        eval_hard_budgets={"default": [3]},
    )
    source = root / "source"
    write_catalog(source, Catalog(methods=[RELEASED_METHOD], smoke_test=True))
    configfile = root / "benchmark.yaml"
    configfile.write_text(yaml.safe_dump(workflow.config))
    record_run_config(source, configfile)
    reviewed = root / "reviewed"
    review = reviewed / "conf/release/dataset_redistribution.yaml"
    review.parent.mkdir(parents=True)
    review.write_text(
        yaml.safe_dump(
            {
                "datasets": {
                    "cube": {
                        "status": "permitted",
                        "bundle_policy": dataset_bundles,
                        "license": "MIT",
                        "source": "generated by afabench",
                        "reviewed_by": "maintainer",
                        "notes": None,
                        "omission_reason": "regenerated by adopters"
                        if dataset_bundles == "omit"
                        else None,
                    }
                }
            }
        )
    )
    runner = CliRunner()
    package = root / "package"
    saved = runner.invoke(
        app,
        [
            "save",
            str(package),
            "--source-root",
            str(source),
            "--configfile",
            str(configfile),
            "--release-id",
            "preview",
            "--checkout",
            str(reviewed),
        ],
    )
    assert saved.exit_code == 0, saved.output
    restored = runner.invoke(
        app,
        ["restore", str(package), "--destination-root", str(workflow.output)],
    )
    assert restored.exit_code == 0, restored.output
    return workflow


def output_root_state(
    workflow: WorkflowHarness,
) -> dict[Path, tuple[bytes, int]]:
    """Return every file of the output root with its bytes and mtime."""
    return {
        path: (path.read_bytes(), path.stat().st_mtime_ns)
        for path in workflow.output.rglob("*")
        if path.is_file()
    }


def statuses(plan: PipelinePlan) -> dict[Key, str]:
    """Index the jobs' statuses by rule, method and dataset realization."""
    indexed = {
        (
            job.rule,
            job.wildcards.get("method"),
            job.wildcards["dataset_realization_index"],
        ): job.status
        for job in plan.jobs
    }
    assert len(indexed) == len(plan.jobs)
    return indexed


def test_released_outputs_on_omitted_datasets_are_conditionally_reused(
    tmp_path: Path,
) -> None:
    workflow = restored_release(tmp_path, dataset_bundles="omit")
    assert not list(workflow.output.glob("datasets/**/*.bundle"))
    before = output_root_state(workflow)

    plan = workflow.planned_graph(
        "--executor", "local", configuration_source=EXTENDED_RELEASE
    )

    assert statuses(plan) == {
        # Released alpha on realization 0 waits for its datasets' checks.
        ("dataset_generation", None, "0"): "run",
        ("train_classifier", None, "0"): "conditional_reuse",
        ("train_method", "alpha", "0"): "conditional_reuse",
        ("eval_method", "alpha", "0"): "conditional_reuse",
        # What the release does not cover runs.
        ("train_method", "beta", "0"): "run",
        ("eval_method", "beta", "0"): "run",
        ("dataset_generation", None, "1"): "run",
        ("train_classifier", None, "1"): "run",
        ("train_method", "alpha", "1"): "run",
        ("eval_method", "alpha", "1"): "run",
        ("train_method", "beta", "1"): "run",
        ("eval_method", "beta", "1"): "run",
    }
    jobs = {
        (
            job.rule,
            job.wildcards.get("method"),
            job.wildcards["dataset_realization_index"],
        ): job
        for job in plan.jobs
    }
    datasets = workflow.output / "datasets/cube/0"
    assert [
        (reason.kind, reason.files)
        for reason in jobs[("train_classifier", None, "0")].reasons
    ] == [
        (
            "pending_dataset_check",
            (str(datasets / "train.bundle"), str(datasets / "val.bundle")),
        )
    ]
    classifier = workflow.output / (
        "trained_classifiers/initializer-cold/"
        "dataset-cube+realization_index-0.bundle"
    )
    assert [
        (reason.kind, reason.files)
        for reason in jobs[("train_method", "alpha", "0")].reasons
    ] == [
        (
            "pending_dataset_check",
            (str(datasets / "train.bundle"), str(datasets / "val.bundle")),
        ),
        ("conditional_input", (str(classifier),)),
    ]
    # The compute estimate counts them among the scheduled jobs, as before.
    assert len(plan.scheduled_jobs) == len(plan.jobs)
    assert output_root_state(workflow) == before
    assert workflow.submissions() == []
    assert not workflow.arguments.exists()


def test_a_released_output_that_is_missing_runs_over_conditional_reuse(
    tmp_path: Path,
) -> None:
    workflow = restored_release(tmp_path, dataset_bundles="omit")
    (workflow.output / "eval_results" / RELEASED_EVALUATION).unlink()

    plan = workflow.planned_graph(
        "--executor", "local", configuration_source=RELEASE
    )

    assert statuses(plan) == {
        ("dataset_generation", None, "0"): "run",
        ("train_classifier", None, "0"): "conditional_reuse",
        ("train_method", "alpha", "0"): "conditional_reuse",
        ("eval_method", "alpha", "0"): "run",
    }
    evaluation = next(job for job in plan.jobs if job.rule == "eval_method")
    assert [reason.kind for reason in evaluation.reasons] == [
        "missing_output",
        "input_from_rerun",
    ]


def test_released_outputs_on_restored_datasets_are_reused(
    tmp_path: Path,
) -> None:
    workflow = restored_release(tmp_path, dataset_bundles="include")
    before = output_root_state(workflow)

    plan = workflow.planned_graph(
        "--executor", "local", configuration_source=EXTENDED_RELEASE
    )

    # The datasets exist, so planning has checked their content already.
    assert statuses(plan) == {
        ("dataset_generation", None, "0"): "reuse",
        ("train_classifier", None, "0"): "reuse",
        ("train_method", "alpha", "0"): "reuse",
        ("eval_method", "alpha", "0"): "reuse",
        ("train_method", "beta", "0"): "run",
        ("eval_method", "beta", "0"): "run",
        ("dataset_generation", None, "1"): "run",
        ("train_classifier", None, "1"): "run",
        ("train_method", "alpha", "1"): "run",
        ("eval_method", "alpha", "1"): "run",
        ("train_method", "beta", "1"): "run",
        ("eval_method", "beta", "1"): "run",
    }
    assert output_root_state(workflow) == before
    assert workflow.submissions() == []


def test_an_incompatible_restored_dataset_fails_the_preview(
    tmp_path: Path,
) -> None:
    workflow = restored_release(tmp_path, dataset_bundles="include")
    data = workflow.output / "datasets/cube/0/train.bundle/data/weights.bin"
    data.write_text("changed")
    before = output_root_state(workflow)
    app = PipelinePreviewApp(
        PlanningProcess(
            workflow.invocation_arguments(
                "--executor", "local", configuration_source=RELEASE
            ),
            cwd=workflow.root,
            env=workflow.environment(),
        )
    )

    async def wait_for_planning() -> None:
        async with app.run_test() as pilot:
            deadline = time.monotonic() + 240
            while (
                app.planning_state == "planning"
                and time.monotonic() < deadline
            ):
                await pilot.pause(0.2)
            await pilot.press("q")

    asyncio.run(wait_for_planning())

    # No partial graph: the failure and its diagnostics, and exit status 1.
    assert app.planning_state == "failed"
    assert app.plan is None
    assert "Incompatible dataset" in app.diagnostics
    assert app.return_code == 1
    assert output_root_state(workflow) == before
    assert workflow.submissions() == []
