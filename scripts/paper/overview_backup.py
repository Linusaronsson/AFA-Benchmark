"""
Sampling distributions of the root Bellman action-values, per approach.

The overview figure needs a landscape the three approaches can be placed on.
The natural one is the pair of estimated action-values at the root of
Example 1: what each approach believes acquiring the context is worth, against
what it believes the shortcut is worth. The diagonal is the decision boundary,
so which side of it a draw lands on is which first acquisition the resulting
policy makes.

Everything here is Monte Carlo over the same generative process the exact
control study uses; the estimators are the ones in scripts/paper/exact_study.py.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
from exact_study import (
    ARM_AGNOSTIC,
    ARM_GENERATIVE,
    ARM_LOCAL,
    BUDGET,
    CONTEXT,
    LAPLACE,
    SHORTCUT,
    Dataset,
    FixedPredictor,
    IntArray,
    Problem,
    _base_plan_quantities,
    _smoothed_probability,
    build_count_tables,
)

ARMS = (ARM_AGNOSTIC, ARM_LOCAL, ARM_GENERATIVE)


def _root_values_model_based(
    tables, costs: IntArray, predictor: FixedPredictor
):
    """
    The root action-values behind plan_model_based, kept rather than discarded.

    Mirrors the loop in exact_study.plan_model_based; the study needs only the
    resulting plan, whereas the figure needs the values themselves.
    """
    quantities = _base_plan_quantities(tables, costs, predictor)
    root_q = np.full(len(costs), -np.inf, dtype=np.float64)
    for action, cost in enumerate(costs):
        if cost > BUDGET:
            continue
        counts = tables.single_count[action]
        p_one = float(_smoothed_probability(counts[1], counts.sum()))
        values = quantities.single_stop[action].copy()
        if cost < BUDGET:
            values = np.maximum(values, quantities.q_last[action].max(axis=1))
        root_q[action] = (1 - p_one) * values[0] + p_one * values[1]
    return root_q


def _root_values_agnostic(data: Dataset, tables, costs: IntArray, predictor):
    """The root action-values behind plan_mask_agnostic."""
    quantities = _base_plan_quantities(tables, costs, predictor)
    root_q = np.full(len(costs), -np.inf, dtype=np.float64)
    for action, cost in enumerate(costs):
        if cost > BUDGET:
            continue
        selected = data.available[:, action]
        count = int(selected.sum())
        if count == 0:
            root_q[action] = 0.5
            continue
        values = quantities.single_stop[action, data.x[:, action]].copy()
        for continuation, continuation_cost in enumerate(costs):
            if cost + continuation_cost > BUDGET:
                continue
            candidate = quantities.q_last[
                action, data.x[:, action], continuation
            ]
            values = np.where(
                data.available[:, continuation],
                np.maximum(values, candidate),
                values,
            )
        root_q[action] = (float(values[selected].sum()) + LAPLACE) / (
            count + 2 * LAPLACE
        )
    return root_q


def draws(d: int, p_miss: float, n: int, reps: int, seed: int):
    """One (context, shortcut) action-value pair per approach per replication."""
    problem = Problem(d)
    predictor = problem.fixed_predictor()
    out = {arm: np.empty((reps, 2)) for arm in ARMS}
    for rep in range(reps):
        rng = np.random.default_rng(
            np.random.SeedSequence((seed, d, round(1000 * p_miss), n, rep))
        )
        data = problem.sample(rng, n, p_miss)
        pooled = build_count_tables(data)
        complete_only = build_count_tables(data, complete_only=True)
        values = {
            ARM_AGNOSTIC: _root_values_agnostic(
                data, pooled, problem.costs, predictor
            ),
            ARM_LOCAL: _root_values_model_based(
                complete_only, problem.costs, predictor
            ),
            ARM_GENERATIVE: _root_values_model_based(
                pooled, problem.costs, predictor
            ),
        }
        for arm, root_q in values.items():
            out[arm][rep] = (root_q[CONTEXT], root_q[SHORTCUT])
    return out


# The landscape the clouds are drawn on. Both axes share a scale so the
# decision boundary is a true 45 degree line.
LO, HI, SPAN_CM = 0.45, 1.02, 5.15
PANELS = (1000, 10000)
FIG_D, FIG_P, FIG_REPS, FIG_SEED = 6, 0.7, 200, 0
WORDS = ["Zero", "One", "Two", "Three", "Four", "Five"]
CODE = {
    "mask_agnostic": "Alias",
    "mask_local": "Filter",
    "generative": "Restore",
}


def _cm(value: float) -> float:
    return (value - LO) / (HI - LO) * SPAN_CM


def render() -> str:
    problem = Problem(FIG_D)
    truth_ctx = problem.optimal_value()
    lines = [
        "% Generated by scripts/paper/overview_backup.py.",
        "% Regenerate rather than editing by hand.",
        rf"\newcommand{{\bkD}}{{{FIG_D}}}",
        rf"\newcommand{{\bkP}}{{{FIG_P:g}}}",
        rf"\newcommand{{\bkReps}}{{{FIG_REPS}}}",
        rf"\newcommand{{\bkSpan}}{{{SPAN_CM:g}}}",
        rf"\newcommand{{\bkTruthX}}{{{_cm(1.0):.3f}}}",
        rf"\newcommand{{\bkTruthY}}{{{_cm(0.75):.3f}}}",
        rf"\newcommand{{\bkDiagLo}}{{{_cm(LO):.3f}}}",
        rf"\newcommand{{\bkDiagHi}}{{{_cm(0.85):.3f}}}",
    ]
    # Axis ticks, in figure centimetres.
    for value in (0.5, 0.6, 0.7, 0.8, 0.9, 1.0):
        tag = WORDS[int(round((value - 0.5) * 10))] if value < 1.0 else "Ten"
        lines.append(rf"\newcommand{{\bkTick{tag}}}{{{_cm(value):.3f}}}")
    for index, n in enumerate(PANELS, start=1):
        word = WORDS[index]
        result = draws(FIG_D, FIG_P, n, FIG_REPS, FIG_SEED)
        lines.append(
            rf"\newcommand{{\bkN{word}}}{{{n:,}}}".replace(",", "{,}")
        )
        for arm, pairs in result.items():
            code = CODE[arm]
            pts = " ".join(f"({_cm(a):.3f},{_cm(b):.3f})" for a, b in pairs)
            lines.append(rf"\newcommand{{\bk{code}{word}}}{{{pts}}}")
            share = float((pairs[:, 0] > pairs[:, 1]).mean())
            lines.append(
                rf"\newcommand{{\bk{code}{word}Share}}{{{share * 100:.0f}\%}}"
            )
            med = np.median(pairs, axis=0)
            lines.append(
                rf"\newcommand{{\bk{code}{word}Med}}"
                rf"{{{_cm(med[0]):.3f}/{_cm(med[1]):.3f}}}"
            )
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--d", type=int, default=6)
    parser.add_argument("--p", type=float, default=0.7)
    parser.add_argument("--n", type=int, nargs="+", default=[316])
    parser.add_argument("--reps", type=int, default=400)
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    if args.output is not None:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(render())
        print(f"wrote {args.output}")
        return
    for n in args.n:
        result = draws(args.d, args.p, n, args.reps, args.seed)
        print(f"\nd={args.d} p={args.p} n={n} reps={args.reps}")
        for arm, pairs in result.items():
            ctx, sc = pairs[:, 0], pairs[:, 1]
            picks_context = float((ctx > sc).mean())
            print(
                f"  {arm:15s} context {ctx.mean():.3f}+-{ctx.std():.3f}"
                f"  shortcut {sc.mean():.3f}+-{sc.std():.3f}"
                f"  picks context {picks_context:5.1%}"
            )


if __name__ == "__main__":
    main()
