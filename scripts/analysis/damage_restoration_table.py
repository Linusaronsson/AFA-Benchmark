"""
Render the damage and restoration table for `sec:exp-main`.

Reads the per-cell CSV that `plot_main_summary.py --table` writes, so the table
and the figure cannot disagree: both come from one pass over the same
`instance_metrics.csv` at each dataset's largest budget, in that dataset's
predeclared primary metric.

`D` is the missingness damage, complete minus direct. `R` is the restoration
gain, label-conditioned PVAE minus direct. Both are per method, never pooled
across methods, and every subtraction holds the dataset, instance, budget,
mechanism and rate fixed.
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import cast

import pandas as pd

from afabench.plotting.methods import (
    DATASET_LABELS_SHORT,
    MECHANISM_LABELS,
    METHOD_LABELS,
    PRIMARY_METHODS,
)

# Short forms, because the table has one row per dataset and method and the
# full state descriptions do not fit a two-column layout.
METHOD_SHORT = {
    "aaco": "AACO",
    "dime": "DIME",
    "ol_with_mask": "OL (acq.\\ mask)",
    "ol_full_state": "OL (full state)",
}


def _column(frame: pd.DataFrame, name: str) -> pd.Series:
    return cast("pd.Series", frame[name])


def _rows(frame: pd.DataFrame, mask: pd.Series) -> pd.DataFrame:
    return cast("pd.DataFrame", frame[mask])


def render(frame: pd.DataFrame, mechanism: str) -> str:
    cells = _rows(frame, _column(frame, "mechanism") == mechanism)
    if cells.empty:
        message = f"no cells for mechanism {mechanism}"
        raise SystemExit(message)
    rates = sorted({float(value) for value in _column(cells, "p")})

    # A complete float, so regenerating updates the paper with no LaTeX edit.
    lines = [
        "% Generated by scripts/analysis/damage_restoration_table.py.",
        "% Regenerate rather than editing by hand.",
        "\\begin{table}[t]",
        "\\centering",
        "\\small",
        f"\\caption{{Missingness damage $D$ and restoration gain $R$ under "
        f"{MECHANISM_LABELS.get(mechanism, mechanism)}, per dataset, method "
        f"and rate, at each dataset's largest budget in its primary metric.}}",
        f"\\label{{tab:dr-{mechanism.replace('_', '-')}}}",
        "\\begin{tabular}{ll" + "rr" * len(rates) + "}",
        "\\toprule",
        "& & "
        + " & ".join(
            f"\\multicolumn{{2}}{{c}}{{$p={rate:g}$}}" for rate in rates
        )
        + " \\\\",
        "Dataset & Method & "
        + " & ".join(["$D$ & $R$"] * len(rates))
        + " \\\\",
        "\\midrule",
    ]
    for dataset in sorted({str(value) for value in _column(cells, "dataset")}):
        per_dataset = _rows(cells, _column(cells, "dataset") == dataset)
        first = True
        for method in PRIMARY_METHODS:
            per_method = _rows(
                per_dataset, _column(per_dataset, "method") == method
            )
            if per_method.empty:
                continue
            values = []
            for rate in rates:
                cell = _rows(per_method, _column(per_method, "p") == rate)
                if cell.empty:
                    values += ["--", "--"]
                    continue
                values += [
                    f"${float(cell['damage'].mean()):+.3f}$",
                    f"${float(cell['gain'].mean()):+.3f}$",
                ]
            label = DATASET_LABELS_SHORT.get(dataset, dataset) if first else ""
            lines.append(
                f"{label} & {METHOD_SHORT.get(method, METHOD_LABELS[method])}"
                f" & " + " & ".join(values) + " \\\\"
            )
            first = False
        lines.append("\\addlinespace")
    if lines[-1] == "\\addlinespace":
        lines.pop()
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--cells",
        type=Path,
        required=True,
        help="CSV written by plot_main_summary.py --table",
    )
    parser.add_argument("--mechanism", default="mcar")
    parser.add_argument("--output", type=Path, required=True)
    arguments = parser.parse_args()

    frame = pd.read_csv(arguments.cells)
    body = render(frame, arguments.mechanism)
    arguments.output.parent.mkdir(parents=True, exist_ok=True)
    arguments.output.write_text(body + "\n")
    print(body)
    print(f"\nwrote {arguments.output}")


if __name__ == "__main__":
    main()
